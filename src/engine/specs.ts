export function clampAndStep(value: number, spec: ParameterSpec): number {
  const clamped = Math.max(spec.min, Math.min(spec.max, value));
  const steps = Math.round((clamped - spec.min) / spec.step);
  const stepped = spec.min + steps * spec.step;
  const factor = Math.pow(10, spec.decimals);
  return Math.round(Math.max(spec.min, Math.min(spec.max, stepped)) * factor) / factor;
}

export function formatParamValue(value: number, spec: ParameterSpec): string {
  return `${value.toFixed(spec.decimals)}${spec.unit}`;
}
